//go:build ignore

// Command lookalikes_gen writes lookalikes.go from Unicode's confusables.txt (UTS #39), for Impersonates (R-122):
//
//	curl -sO https://www.unicode.org/Public/security/latest/confusables.txt
//	go run lookalikes_gen.go < confusables.txt > lookalikes.go
//
// It keeps each character whose prototype is one ASCII letter, as that letter in lower case.
package main

import (
	"bufio"
	"fmt"
	"os"
	"slices"
	"strconv"
	"strings"
	"unicode"
)

func main() {
	version := ""
	table := map[rune]rune{}
	in := bufio.NewScanner(os.Stdin)
	for in.Scan() {
		line := in.Text()
		if v, ok := strings.CutPrefix(line, "# Version: "); ok {
			version = v
		}
		fields := strings.Split(strings.SplitN(line, "#", 2)[0], ";")
		if len(fields) < 2 {
			continue
		}
		source, err1 := strconv.ParseUint(strings.TrimSpace(fields[0]), 16, 32)
		target, err2 := strconv.ParseUint(strings.TrimSpace(fields[1]), 16, 32)
		if err1 != nil || err2 != nil || target > unicode.MaxASCII || !unicode.IsLetter(rune(target)) {
			continue // one code point that reads as an ASCII letter, nothing else
		}
		table[rune(source)] = unicode.ToLower(rune(target))
	}
	if err := in.Err(); err != nil || version == "" || len(table) == 0 {
		fmt.Fprintln(os.Stderr, "lookalikes_gen: read confusables.txt on stdin:", err)
		os.Exit(1)
	}
	sources := slices.Sorted(func(yield func(rune) bool) {
		for r := range table {
			if !yield(r) {
				return
			}
		}
	})
	fmt.Printf("// Code generated by lookalikes_gen.go from Unicode confusables.txt %s; DO NOT EDIT.\n\n", version)
	fmt.Print("package profile\n\n// lookalikes maps each character that reads as one ASCII letter to that letter in lower case.\n")
	fmt.Print("var lookalikes = map[rune]byte{")
	for i, r := range sources {
		if i%8 == 0 {
			fmt.Print("\n\t")
		} else {
			fmt.Print(" ")
		}
		fmt.Printf("0x%04x: '%c',", r, table[r])
	}
	fmt.Print("\n}\n")
}
